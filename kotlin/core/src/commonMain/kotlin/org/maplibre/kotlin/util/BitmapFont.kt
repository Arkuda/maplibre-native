    /** Rows of the given ASCII char as bitmasks (LSB = leftmost pixel). */
    fun glyph(c: Char): IntArray {
        val code = c.code
        if (code < 32 || code > 126) return IntArray(GLYPH_HEIGHT)
        val base = (code - 32) * GLYPH_HEIGHT
        return IntArray(GLYPH_HEIGHT) { i -> FONT[base + i] }
    }

    /** Width in pixels of a string at the given scale. */
    fun measure(text: String, size: Float): Float = text.length * ADVANCE * (size / 12f)

    fun isValid(c: Char): Boolean = c.code in 32..126
